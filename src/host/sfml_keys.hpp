// Neutral keys to SFML scancodes: physical positions, layout independent, which is what the
// original's keyboard interrupt saw (KeyboardHandler, 1:0dcc, stores raw key codes).
constexpr std::int32_t Code(sf::Keyboard::Scancode scancode) {
  return std::to_underlying(scancode);
}

